//! CIEDE2000 色差度量与 sRGB → CIELAB 转换（Sharma et al. 2005）。
//!
//! 决策记录：不引入 `deltae` crate —— 自实现约 80 行 + Sharma 论文官方 34 组
//! 测试向量锚定（TR-1.1，容差 1e-4），测试侧零新增依赖、零供应链风险。
//! 公式参考：Sharma, Wu, Dalal, "The CIEDE2000 Color-Difference Formula:
//! Implementation Notes, Supplementary Test Data, and Mathematical Observations".

const XN: f64 = 0.95047;
const YN: f64 = 1.0;
const ZN: f64 = 1.08883;

/// sRGB 8bit → 线性值（IEC 61966-2-1 精确传递曲线，非简化 gamma 2.2）
fn srgb_eotf(c: f64) -> f64 {
    let c = c / 255.0;
    if c <= 0.04045 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    }
}

/// 线性 RGB → XYZ（D65 白点，sRGB/Rec.709 原色矩阵）
fn linear_rgb_to_xyz(r: f64, g: f64, b: f64) -> [f64; 3] {
    [
        0.4124564 * r + 0.3575761 * g + 0.1804375 * b,
        0.2126729 * r + 0.7151522 * g + 0.0721750 * b,
        0.0193339 * r + 0.1191920 * g + 0.9503041 * b,
    ]
}

fn f_lab(t: f64) -> f64 {
    const DELTA: f64 = 6.0 / 29.0;
    if t > DELTA * DELTA * DELTA {
        t.cbrt()
    } else {
        t / (3.0 * DELTA * DELTA) + 4.0 / 29.0
    }
}

/// sRGB 8bit 像素 → CIELAB [L, a, b]（D65）
pub fn srgb8_to_lab(rgb: [u8; 3]) -> [f64; 3] {
    let lin = [
        srgb_eotf(rgb[0] as f64),
        srgb_eotf(rgb[1] as f64),
        srgb_eotf(rgb[2] as f64),
    ];
    let xyz = linear_rgb_to_xyz(lin[0], lin[1], lin[2]);
    let fx = f_lab(xyz[0] / XN);
    let fy = f_lab(xyz[1] / YN);
    let fz = f_lab(xyz[2] / ZN);
    [116.0 * fy - 16.0, 500.0 * (fx - fy), 200.0 * (fy - fz)]
}

fn atan2_deg(y: f64, x: f64) -> f64 {
    let deg = y.atan2(x).to_degrees();
    if deg < 0.0 { deg + 360.0 } else { deg }
}

/// 色相差：按 Sharma 补充规则处理 360° 环绕
fn hue_diff(h1: f64, h2: f64) -> f64 {
    if (h2 - h1).abs() <= 180.0 {
        h2 - h1
    } else if h2 <= h1 {
        h2 - h1 + 360.0
    } else {
        h2 - h1 - 360.0
    }
}

/// 平均色相：按 Sharma 补充规则处理 360° 环绕
fn mean_hue(h1: f64, h2: f64) -> f64 {
    if (h1 - h2).abs() > 180.0 && h1 + h2 < 360.0 {
        (h1 + h2 + 360.0) / 2.0
    } else if (h1 - h2).abs() > 180.0 && h1 + h2 >= 360.0 {
        (h1 + h2 - 360.0) / 2.0
    } else {
        (h1 + h2) / 2.0
    }
}

fn deg_cos(d: f64) -> f64 {
    d.to_radians().cos()
}

fn deg_sin(d: f64) -> f64 {
    d.to_radians().sin()
}

/// CIEDE2000 色差。输入 CIELAB [L, a, b]。
pub fn delta_e_2000(lab1: &[f64; 3], lab2: &[f64; 3]) -> f64 {
    let (l1, a1, b1) = (lab1[0], lab1[1], lab1[2]);
    let (l2, a2, b2) = (lab2[0], lab2[1], lab2[2]);

    let c1 = (a1 * a1 + b1 * b1).sqrt();
    let c2 = (a2 * a2 + b2 * b2).sqrt();
    let c_bar = (c1 + c2) / 2.0;
    let c_bar7 = c_bar.powi(7);
    let g = 0.5 * (1.0 - (c_bar7 / (c_bar7 + 25f64.powi(7))).sqrt());

    let a1p = (1.0 + g) * a1;
    let a2p = (1.0 + g) * a2;
    let c1p = (a1p * a1p + b1 * b1).sqrt();
    let c2p = (a2p * a2p + b2 * b2).sqrt();

    let h1p = if b1 == 0.0 && a1p == 0.0 {
        0.0
    } else {
        atan2_deg(b1, a1p)
    };
    let h2p = if b2 == 0.0 && a2p == 0.0 {
        0.0
    } else {
        atan2_deg(b2, a2p)
    };

    let dl = l2 - l1;
    let dc = c2p - c1p;

    let dhp = if c1p * c2p == 0.0 {
        0.0
    } else {
        hue_diff(h1p, h2p)
    };
    let dh = 2.0 * (c1p * c2p).sqrt() * (dhp.to_radians() / 2.0).sin();

    let l_bar_p = (l1 + l2) / 2.0;
    let c_bar_p = (c1p + c2p) / 2.0;
    let h_bar_p = if c1p * c2p == 0.0 {
        h1p + h2p
    } else {
        mean_hue(h1p, h2p)
    };

    let t = 1.0 - 0.17 * deg_cos(h_bar_p - 30.0)
        + 0.24 * deg_cos(2.0 * h_bar_p)
        + 0.32 * deg_cos(3.0 * h_bar_p + 6.0)
        - 0.20 * deg_cos(4.0 * h_bar_p - 63.0);

    let delta_theta = 30.0 * (-(((h_bar_p - 275.0) / 25.0).powi(2))).exp();
    let c_bar_p7 = c_bar_p.powi(7);
    let sl = 1.0 + 0.015 * (l_bar_p - 50.0).powi(2) / (20.0 + (l_bar_p - 50.0).powi(2)).sqrt();
    let sc = 1.0 + 0.045 * c_bar_p;
    let sh = 1.0 + 0.015 * c_bar_p * t;
    let rt = -2.0 * (c_bar_p7 / (c_bar_p7 + 25f64.powi(7))).sqrt() * deg_sin(2.0 * delta_theta);

    let term_l = dl / sl;
    let term_c = dc / sc;
    let term_h = dh / sh;
    (term_l * term_l + term_c * term_c + term_h * term_h + rt * term_c * term_h).sqrt()
}

