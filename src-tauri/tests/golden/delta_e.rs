    #[test]
    fn sharma_2005_vectors() {
        for (i, (lab1, lab2, expected)) in SHARMA.iter().enumerate() {
            let de = delta_e_2000(lab1, lab2);
            assert!(
                (de - expected).abs() < 1e-4,
                "vector {}: got {de}, expected {expected}",
                i + 1
            );
        }
    }

    /// 对称性：ΔE(a,b) == ΔE(b,a)（CIEDE2000 数学性质）
    #[test]
    fn symmetric() {
        let a = [41.24, 5.31, -12.44];
        let b = [63.01, -31.09, -5.86];
        assert!((delta_e_2000(&a, &b) - delta_e_2000(&b, &a)).abs() < 1e-12);
    }

    /// sRGB 锚点：白/黑/中灰的 L* 与理论值吻合
    #[test]
    fn srgb_anchors() {
        let white = srgb8_to_lab([255, 255, 255]);
        // 矩阵系数 7 位截断 → L*/a*/b* 有 ~1e-5 级残差（对 0.5 量级 ΔE 阈值可忽略）
        assert!((white[0] - 100.0).abs() < 1e-4, "white L*: {}", white[0]);
        assert!(white[1].abs() < 1e-3 && white[2].abs() < 1e-3);

        let black = srgb8_to_lab([0, 0, 0]);
        assert!((black[0]).abs() < 1e-9, "black L*: {}", black[0]);

        let gray = srgb8_to_lab([128, 128, 128]);
        assert!((gray[0] - 53.585).abs() < 0.01, "gray L*: {}", gray[0]);
        assert!(gray[1].abs() < 1e-3 && gray[2].abs() < 1e-3);
    }
